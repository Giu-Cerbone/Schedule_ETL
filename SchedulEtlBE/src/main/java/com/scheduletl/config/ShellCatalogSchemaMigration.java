package com.scheduletl.config;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import com.fasterxml.jackson.databind.node.ObjectNode;
import org.springframework.boot.ApplicationArguments;
import org.springframework.boot.ApplicationRunner;
import org.springframework.core.Ordered;
import org.springframework.core.annotation.Order;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.support.GeneratedKeyHolder;
import org.springframework.jdbc.support.KeyHolder;
import org.springframework.stereotype.Component;

import java.nio.file.Path;
import java.sql.PreparedStatement;
import java.sql.Statement;
import java.util.HashMap;
import java.util.List;
import java.util.Map;

@Component
@Order(Ordered.HIGHEST_PRECEDENCE)
public class ShellCatalogSchemaMigration implements ApplicationRunner {

    private final JdbcTemplate jdbc;
    private final ObjectMapper objectMapper;

    public ShellCatalogSchemaMigration(JdbcTemplate jdbc, ObjectMapper objectMapper) {
        this.jdbc = jdbc;
        this.objectMapper = objectMapper;
    }

    @Override
    public void run(ApplicationArguments args) {
        Map<String, Long> commandIds = migrateCommands();
        Map<String, Long> scriptIds = migrateScripts();
        if (!commandIds.isEmpty() || !scriptIds.isEmpty()) {
            migrateProcessConfigurations(commandIds, scriptIds);
        }
    }

    private Map<String, Long> migrateCommands() {
        if (!tableExists("AUTHORIZED_SHELL_COMMANDS")) {
            return Map.of();
        }
        if (!isLegacyIdColumn("AUTHORIZED_SHELL_COMMANDS", "ID")) {
            migrateCommandNameAndIdentity();
            return Map.of();
        }

        List<LegacyCommand> commands = jdbc.query("""
                SELECT id, label, type, executable FROM authorized_shell_commands ORDER BY id
                """, (rs, row) -> new LegacyCommand(rs.getString("id"), rs.getString("label"),
                rs.getString("type"), rs.getString("executable")));
        List<LegacyArgument> arguments = tableExists("AUTHORIZED_SHELL_COMMAND_ARGUMENTS")
                ? jdbc.query("""
                    SELECT command_id, argument_order, argument_value
                    FROM authorized_shell_command_arguments ORDER BY command_id, argument_order
                    """, (rs, row) -> new LegacyArgument(rs.getString("command_id"),
                    rs.getInt("argument_order"), rs.getString("argument_value")))
                : List.of();

        jdbc.execute("DROP TABLE IF EXISTS authorized_shell_command_arguments_new");
        jdbc.execute("DROP TABLE IF EXISTS authorized_shell_commands_new");
        jdbc.execute("""
                CREATE TABLE authorized_shell_commands_new (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(255) NOT NULL,
                    type VARCHAR(255) NOT NULL,
                    executable VARCHAR(2048) NOT NULL
                )
                """);
        jdbc.execute("""
                CREATE TABLE authorized_shell_command_arguments_new (
                    argument_order INTEGER NOT NULL,
                    command_id BIGINT NOT NULL,
                    argument_value VARCHAR(2048) NOT NULL,
                    PRIMARY KEY (argument_order, command_id)
                )
                """);

        Map<String, Long> idMap = new HashMap<>();
        for (LegacyCommand command : commands) {
            KeyHolder key = new GeneratedKeyHolder();
            jdbc.update(connection -> {
                PreparedStatement statement = connection.prepareStatement("""
                        INSERT INTO authorized_shell_commands_new (name, type, executable) VALUES (?, ?, ?)
                        """, Statement.RETURN_GENERATED_KEYS);
                statement.setString(1, command.label());
                statement.setString(2, command.type());
                statement.setString(3, command.executable());
                return statement;
            }, key);
            Number generatedId = key.getKey();
            if (generatedId == null) {
                throw new IllegalStateException("The database did not generate an ID while migrating authorized commands.");
            }
            idMap.put(command.id(), generatedId.longValue());
        }
        for (LegacyArgument argument : arguments) {
            Long commandId = idMap.get(argument.commandId());
            if (commandId != null) {
                jdbc.update("""
                        INSERT INTO authorized_shell_command_arguments_new
                            (argument_order, command_id, argument_value) VALUES (?, ?, ?)
                        """, argument.order(), commandId, argument.value());
            }
        }

        jdbc.execute("DROP TABLE IF EXISTS authorized_shell_command_arguments");
        jdbc.execute("DROP TABLE authorized_shell_commands");
        jdbc.execute("ALTER TABLE authorized_shell_commands_new RENAME TO authorized_shell_commands");
        jdbc.execute("ALTER TABLE authorized_shell_command_arguments_new RENAME TO authorized_shell_command_arguments");
        jdbc.execute("""
                ALTER TABLE authorized_shell_command_arguments
                ADD CONSTRAINT fk_authorized_command_arguments_command
                FOREIGN KEY (command_id) REFERENCES authorized_shell_commands(id)
                """);
        return idMap;
    }

    private Map<String, Long> migrateScripts() {
        if (!tableExists("REGISTERED_SHELL_SCRIPTS")) {
            return Map.of();
        }
        String oldIdColumn = columnExists("REGISTERED_SHELL_SCRIPTS", "FILE_NAME") ? "FILE_NAME" : "ID";
        if (!isLegacyIdColumn("REGISTERED_SHELL_SCRIPTS", oldIdColumn)) {
            migrateScriptNameAndIdentity();
            return Map.of();
        }

        List<LegacyScript> scripts = jdbc.query(
                "SELECT " + oldIdColumn + ", path FROM registered_shell_scripts ORDER BY " + oldIdColumn,
                (rs, row) -> new LegacyScript(rs.getString(1), rs.getString("path")));
        jdbc.execute("DROP TABLE IF EXISTS registered_shell_scripts_new");
        jdbc.execute("""
                CREATE TABLE registered_shell_scripts_new (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    name VARCHAR(255) NOT NULL,
                    path VARCHAR(2048) NOT NULL UNIQUE
                )
                """);

        Map<String, Long> idMap = new HashMap<>();
        for (LegacyScript script : scripts) {
            KeyHolder key = new GeneratedKeyHolder();
            jdbc.update(connection -> {
                PreparedStatement statement = connection.prepareStatement("""
                        INSERT INTO registered_shell_scripts_new (name, path) VALUES (?, ?)
                        """, Statement.RETURN_GENERATED_KEYS);
                statement.setString(1, Path.of(script.path()).getFileName().toString());
                statement.setString(2, script.path());
                return statement;
            }, key);
            Number generatedId = key.getKey();
            if (generatedId == null) {
                throw new IllegalStateException("The database did not generate an ID while migrating registered scripts.");
            }
            idMap.put(script.id(), generatedId.longValue());
        }

        jdbc.execute("DROP TABLE registered_shell_scripts");
        jdbc.execute("ALTER TABLE registered_shell_scripts_new RENAME TO registered_shell_scripts");
        return idMap;
    }

    private void migrateCommandNameAndIdentity() {
        if (!columnExists("AUTHORIZED_SHELL_COMMANDS", "NAME")
                && columnExists("AUTHORIZED_SHELL_COMMANDS", "LABEL")) {
            jdbc.execute("ALTER TABLE authorized_shell_commands ADD COLUMN name VARCHAR(255)");
            jdbc.execute("UPDATE authorized_shell_commands SET name = label WHERE name IS NULL");
            jdbc.execute("ALTER TABLE authorized_shell_commands ALTER COLUMN name SET NOT NULL");
            jdbc.execute("ALTER TABLE authorized_shell_commands DROP COLUMN label");
        }
        ensureGeneratedPrimaryKey("AUTHORIZED_SHELL_COMMANDS");
    }

    private void migrateScriptNameAndIdentity() {
        if (!columnExists("REGISTERED_SHELL_SCRIPTS", "NAME")
                && columnExists("REGISTERED_SHELL_SCRIPTS", "PATH")) {
            jdbc.execute("ALTER TABLE registered_shell_scripts ADD COLUMN name VARCHAR(255)");
            List<LegacyScript> scripts = jdbc.query("SELECT id, path FROM registered_shell_scripts",
                    (rs, row) -> new LegacyScript(Long.toString(rs.getLong("id")), rs.getString("path")));
            scripts.forEach(script -> jdbc.update("UPDATE registered_shell_scripts SET name = ? WHERE id = ?",
                    Path.of(script.path()).getFileName().toString(), Long.parseLong(script.id())));
            jdbc.execute("ALTER TABLE registered_shell_scripts ALTER COLUMN name SET NOT NULL");
        }
        ensureGeneratedPrimaryKey("REGISTERED_SHELL_SCRIPTS");
    }

    private void ensureGeneratedPrimaryKey(String table) {
        if (!columnExists(table, "ID")) {
            return;
        }
        if (!isPrimaryKey(table, "ID")) {
            jdbc.execute("ALTER TABLE " + table + " ADD PRIMARY KEY (id)");
        }
        if (!isIdentityColumn(table, "ID")) {
            jdbc.execute("ALTER TABLE " + table + " ALTER COLUMN id BIGINT GENERATED BY DEFAULT AS IDENTITY");
        }
        Long maxId = jdbc.queryForObject("SELECT MAX(id) FROM " + table, Long.class);
        jdbc.execute("ALTER TABLE " + table + " ALTER COLUMN id RESTART WITH " + (maxId == null ? 1 : maxId + 1));
    }

    private void migrateProcessConfigurations(Map<String, Long> commandIds, Map<String, Long> scriptIds) {
        if (!tableExists("PROCESS_DEFINITIONS") || !columnExists("PROCESS_DEFINITIONS", "CONFIGURATION")) {
            return;
        }
        List<ProcessConfiguration> configurations = jdbc.query("""
                SELECT id, configuration FROM process_definitions WHERE configuration IS NOT NULL
                """, (rs, row) -> new ProcessConfiguration(rs.getLong("id"), rs.getString("configuration")));
        for (ProcessConfiguration process : configurations) {
            try {
                JsonNode root = objectMapper.readTree(process.configuration());
                if (!(root instanceof ObjectNode object)) continue;
                boolean changed = false;
                changed |= replaceId(object, "commandId", commandIds);
                changed |= replaceId(object, "script", scriptIds);
                if (changed) {
                    jdbc.update("UPDATE process_definitions SET configuration = ? WHERE id = ?",
                            objectMapper.writeValueAsString(object), process.id());
                }
            } catch (Exception exception) {
                throw new IllegalStateException(
                        "Could not migrate shell configuration for process " + process.id() + ".", exception);
            }
        }
    }

    private boolean replaceId(ObjectNode object, String property, Map<String, Long> ids) {
        JsonNode value = object.get(property);
        if (value == null || (!value.isTextual() && !value.isIntegralNumber())) {
            return false;
        }
        Long newId = ids.get(value.asText());
        if (newId == null) {
            return false;
        }
        if (property.equals("script")) {
            object.put(property, newId.toString());
        } else {
            object.put(property, newId);
        }
        return true;
    }

    private boolean tableExists(String table) {
        Integer count = jdbc.queryForObject("""
                SELECT COUNT(*) FROM INFORMATION_SCHEMA.TABLES
                WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ?
                """, Integer.class, table);
        return count > 0;
    }

    private boolean columnExists(String table, String column) {
        Integer count = jdbc.queryForObject("""
                SELECT COUNT(*) FROM INFORMATION_SCHEMA.COLUMNS
                WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ? AND COLUMN_NAME = ?
                """, Integer.class, table, column);
        return count > 0;
    }

    private boolean isLegacyIdColumn(String table, String column) {
        if (!columnExists(table, column)) {
            return false;
        }
        String type = jdbc.queryForObject("""
                SELECT DATA_TYPE FROM INFORMATION_SCHEMA.COLUMNS
                WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ? AND COLUMN_NAME = ?
                """, String.class, table, column);
        return type.contains("CHARACTER") || type.equals("VARCHAR");
    }

    private boolean isIdentityColumn(String table, String column) {
        String identity = jdbc.queryForObject("""
                SELECT IS_IDENTITY FROM INFORMATION_SCHEMA.COLUMNS
                WHERE TABLE_SCHEMA = 'PUBLIC' AND TABLE_NAME = ? AND COLUMN_NAME = ?
                """, String.class, table, column);
        return "YES".equals(identity);
    }

    private boolean isPrimaryKey(String table, String column) {
        Integer count = jdbc.queryForObject("""
                SELECT COUNT(*)
                FROM INFORMATION_SCHEMA.KEY_COLUMN_USAGE k
                JOIN INFORMATION_SCHEMA.TABLE_CONSTRAINTS c
                  ON c.CONSTRAINT_SCHEMA = k.CONSTRAINT_SCHEMA
                 AND c.CONSTRAINT_NAME = k.CONSTRAINT_NAME
                 AND c.TABLE_NAME = k.TABLE_NAME
                WHERE k.TABLE_SCHEMA = 'PUBLIC'
                  AND k.TABLE_NAME = ?
                  AND k.COLUMN_NAME = ?
                  AND c.CONSTRAINT_TYPE = 'PRIMARY KEY'
                """, Integer.class, table, column);
        return count > 0;
    }

    private record LegacyCommand(String id, String label, String type, String executable) {}
    private record LegacyArgument(String commandId, int order, String value) {}
    private record LegacyScript(String id, String path) {}
    private record ProcessConfiguration(long id, String configuration) {}
}
